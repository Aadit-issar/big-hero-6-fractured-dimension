import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { ASSET_SIZES } from '../src/scene/assets/assetSizes';
import { assetSpec } from '../src/scene/assets/assetRegistry';

/** Generates src/shared/assetManifest.ts: the shared asset identity registry. Every entity ATLAS draws names an asset id from this manifest; the
 * manifest records, per id, the canonical GLB levels (path in the Dimension's public/, sha256, triangles) and which level ATLAS draws.
 * ATLAS copies exactly those bytes (scripts/sync-shared-assets.mjs in the ATLAS branch) and tests/assetParity.test.ts compares hashes. */
const root = fileURLToPath(new URL('..', import.meta.url));
const MAX_ATLAS_BYTES = 2_200_000;
const sha = (file: string) => createHash('sha256').update(readFileSync(root + 'public' + file)).digest('hex');

const entries: string[] = [];
for (const [id, sizes] of Object.entries(ASSET_SIZES).sort(([a], [b]) => a.localeCompare(b))) {
  if (id.startsWith('microbot')) continue;
  const spec = assetSpec(id);
  const levels = [{ file: sizes.file, bytes: sizes.bytes, triangles: sizes.triangles }, ...sizes.lods.map(l => ({ file: l.file, bytes: l.bytes, triangles: l.triangles }))];
  // ATLAS draws the nearest level that is small enough to ship twice; the base level is never copied unless it is the only one.
  let atlasLevel = levels.findIndex((l, i) => i > 0 && l.bytes <= MAX_ATLAS_BYTES);
  if (atlasLevel < 0) atlasLevel = levels.length === 1 ? 0 : levels.length - 1;
  const rows = levels.map(l => `{ file: '${l.file}', name: '${l.file.split('/').pop()}', bytes: ${l.bytes}, triangles: ${l.triangles}, sha256: '${sha(l.file)}' }`);
  entries.push(`  ${id}: { id: '${id}', family: '${spec.family}', category: '${spec.category}', size: [${sizes.size.map(v => +v.toFixed(5)).join(', ')}], atlasLevel: ${atlasLevel}, levels: [\n    ${rows.join(',\n    ')},\n  ] },`);
}

// The armoured Baymax hero (Blender-built GLB, branch baymax-armoured-hero of the asset worktree): hero level for the Dimension, LOD1 for ATLAS.
// Bounds (m) are the union of the exported meshes, measured in the asset build: x +-1.70 (wings deployed), y -1.123..+1.239, z -0.468..+0.610.
const heroLevels = [['baymax_hero.glb', 96525], ['baymax_hero_lod1.glb', 18822]].map(([name, triangles]) => {
  const file = `/assets/models/baymax_hero/${name}`;
  const bytes = readFileSync(root + 'public' + file).length;
  return `{ file: '${file}', name: '${name}', bytes: ${bytes}, triangles: ${triangles}, sha256: '${sha(file)}' }`;
});
const heroRows = heroLevels.join(',\n    ');
entries.push(`  baymax_hero: { id: 'baymax_hero', family: 'baymax', category: 'baymax', size: [3.4, 2.369, 1.078], atlasLevel: 1, levels: [\n    ${heroRows},\n  ] },`);

const text = `// Generated by scripts/build-asset-manifest.ts. Do not edit. Byte-identical in the Dimension and ATLAS branches.
/** Shared asset identity: one id, one physical model, in both applications.
 *
 * Conventions (identical in both viewers): 1 world unit = 1 metre; the GLB is placed with its authored origin at the entity position and
 * rotated by the entity's observed quaternion (x, y, z, w); scale 1 (viewers may enlarge a model uniformly for legibility at tactical zoom but
 * never change its proportions); +Y is up. The Dimension draws the nearest level it needs by distance; ATLAS draws \`levels[atlasLevel]\`, a
 * lower level of the SAME model (same silhouette, same material family and texture atlas). */
export interface SharedAssetLevel { readonly file: string; readonly name: string; readonly bytes: number; readonly triangles: number; readonly sha256: string }
export interface SharedAsset {
  readonly id: string;
  readonly family: 'concrete' | 'industrial' | 'baymax' | 'capsule' | 'microbot';
  readonly category: string;
  /** Measured model bounds (m). */
  readonly size: readonly [number, number, number];
  readonly atlasLevel: number;
  readonly levels: readonly SharedAssetLevel[];
}

export const SHARED_ASSETS: Readonly<Record<string, SharedAsset>> = {
${entries.join('\n')}
};

/** The armoured Baymax is one module (src/baymax) plus two GLBs (hero and LOD1, id baymax_hero), copied verbatim into both applications. */
export const BAYMAX_HERO = { id: 'baymax_hero', version: 'armoured-glb-1', heightMetres: 2.25, forward: [0, 0, -1], up: [0, 1, 0] } as const;
`;
writeFileSync(root + 'src/shared/assetManifest.ts', text);
console.log(`wrote ${entries.length} assets`);
