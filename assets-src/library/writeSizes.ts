import { readFileSync, writeFileSync } from 'node:fs';

/** Emits src/scene/assets/assetSizes.ts from the measured manifest, so the scene
 * layout uses the real model bounds without importing from public/ at runtime.
 * Run after buildLibrary: npx tsx assets-src/library/writeSizes.ts */
export function writeAssetSizes(manifestPath = 'public/assets/models/manifest.json', out = 'src/scene/assets/assetSizes.ts'): void {
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8')) as Record<string, { size: [number, number, number]; triangles: number }>;
  const rows = Object.entries(manifest).map(([id, m]) => `  ${id}: { size: [${m.size.map((s) => +s.toFixed(5)).join(', ')}], triangles: ${m.triangles} },`);
  writeFileSync(out, `// Generated by assets-src/library/writeSizes.ts from public/assets/models/manifest.json. Do not edit.\n/** Measured model bounds (metres) and triangle counts of every published GLB. */\nexport const ASSET_SIZES: Readonly<Record<string, { readonly size: readonly [number, number, number]; readonly triangles: number }>> = {\n${rows.join('\n')}\n};\n`);
}

if (process.argv[1]?.replace(/\\/g, '/').endsWith('assets-src/library/writeSizes.ts')) writeAssetSizes();
